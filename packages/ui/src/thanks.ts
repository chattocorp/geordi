/** What an action says to the agent, opened with a word of thanks where it has some. */
export function spoken(id: WorkspaceAction['id'], prompt: string, random = Math.random): string {
	const thanks = THANKS[id];
	return thanks?.length ? `${thanks[Math.floor(random() * thanks.length)]} ${prompt}` : prompt;
}

/** Whether a message is what an action says, whichever thanks it opened with. */
export function says(text: string, prompt: string): boolean {
	return text === prompt || text.endsWith(` ${prompt}`);
}
